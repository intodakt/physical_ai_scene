"""S1 W11: dataset README from the bags themselves (one row per bag, numbers measured, not typed).

    python -m src.sensors.dataset_readme --bags data/bags/ --out docs/s1/DATASET.md
    python -m src.sensors.dataset_readme --bags rec/S1_static_bag rec/S2_bag ... --out DATASET.md

For every bag (a rosbag2 folder or a lone .db3) it reads the topic table, measures FPS, frame gaps
and the RGB <-> depth stamp offset (session_report.timing) and writes a Markdown table plus the
scenario descriptions from SCENARIOS (edit them there). Bags whose name matches no scenario are
listed as "unknown scenario".
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from .bag_replay import BagSource, bag_info
from .session_report import timing

SCENARIOS = {  # name prefix -> (scenario, what it proves, which module mainly uses it)
    "S0": ("Calibration (checkerboard)", "intrinsics + reprojection error", "S1, S2"),
    "S1": ("Static baseline", "localisation drift, relations", "S2, S4"),
    "S2": ("Human movement", "robustness to a moving person", "S6"),
    "S3": ("Object relocation", "IDs and graph updates when objects move", "S4, S6"),
    "S4": ("Unseen object entry", "open vocabulary on held-out objects", "S3"),
    "S5": ("Occlusion / reappear", "re-identification", "S6"),
    "S6": ("Language task run", "question -> verified answer -> ActionGoal", "S5, S7"),
}


def find_bags(paths) -> list[Path]:
    out = []
    for p in map(Path, paths):
        if p.is_file() and p.suffix == ".db3" or (p / "metadata.yaml").exists():
            out.append(p)
        elif p.is_dir():
            out += sorted(q for q in p.iterdir() if (q.is_file() and q.suffix == ".db3") or (q / "metadata.yaml").exists())
    return out


def describe(bag: Path) -> dict:
    src = BagSource(bag)
    info, name = bag_info(src), (bag.stem if bag.is_file() else bag.name)
    t = timing(bag)
    key = next((k for k in SCENARIOS if name.upper().startswith(k)), None)
    scen = SCENARIOS.get(key, ("unknown scenario", "—", "—"))
    off = t.get("rgb_depth_offset_ms", {})
    return {"bag": name, "scenario": scen[0], "proves": scen[1], "used_by": scen[2],
            "duration_s": info["duration_s"], "rgb_frames": t.get("rgb", {}).get("messages"),
            "fps": t.get("rgb", {}).get("fps_measured"), "gaps": t.get("rgb", {}).get("gaps_over_1.5x"),
            "sync_p95_ms": off.get("p95"), "camera_info": t["camera_info_recorded"], "tf": bool(t["tf_topics"]),
            "size_mb": round(sum(f.stat().st_size for f in ([bag] if bag.is_file() else bag.rglob("*")) if f.is_file()) / 1e6, 1)}


def write_readme(rows: list[dict], out: Path) -> Path:
    L = ["# G1 dataset — ZED Mini recordings (S1)", "",
         "Generated by `python -m src.sensors.dataset_readme`; every number is measured from the bag.", "",
         "| Bag | Scenario | Proves | Used by | Duration (s) | RGB frames | FPS | Gaps | RGB↔depth p95 (ms) | camera_info | TF | Size (MB) |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['bag']} | {r['scenario']} | {r['proves']} | {r['used_by']} | {r['duration_s']} | {r['rgb_frames']} | "
                 f"{r['fps']} | {r['gaps']} | {r['sync_p95_ms']} | {'yes' if r['camera_info'] else 'no'} | {'yes' if r['tf'] else 'no'} | {r['size_mb']} |")
    L += ["", "Recording procedure and checks: see `docs/s1/SESSION_CHECKLIST.md`.", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    out.with_suffix(".json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bags", nargs="+", required=True)
    ap.add_argument("--out", default="docs/s1/DATASET.md")
    a = ap.parse_args()
    rows = [describe(b) for b in find_bags(a.bags)]
    print(write_readme(rows, Path(a.out)).read_text())


if __name__ == "__main__":
    main()
